// Generates docs/grammar.md from the frozen grammar section of the engine design spec.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const specPath = resolve(root, ".kiro/specs/curse-engine/design.md");
const outPath = resolve(root, "docs/grammar.md");

const spec = readFileSync(specPath, "utf8");
const section = (title) => {
  const m = spec.match(new RegExp(`^#{2,3} ${title}[^\\n]*\\n([\\s\\S]*?)(?=^#{2,3} |(?![\\s\\S]))`, "m"));
  if (!m) throw new Error(`design.md is missing the section "${title}"`);
  return m[1].trim();
};

const out = [
  "# CurseEngine grammar",
  "",
  "Generated by `pnpm --filter @curseengine/engine run docs:grammar` from `.kiro/specs/curse-engine/design.md`. Do not edit by hand.",
  "",
  "## Frozen grammar",
  "",
  section("Frozen grammar"),
  "",
  "## Parser interpretations",
  "",
  section("Parser interpretations"),
  "",
  "## Grammar notes",
  "",
  section("Grammar notes"),
  "",
  "## Executor semantics",
  "",
  section("Executor semantics"),
  "",
].join("\n");

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`Wrote ${outPath}`);
